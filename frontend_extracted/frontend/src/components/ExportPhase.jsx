import { useState } from 'react'
import { Download, Video, FileCode, CheckCircle, AlertTriangle, Clock, Film, Mic, Type } from 'lucide-react'
import ChannelHeader from './ChannelHeader'

// ── XML Generator ────────────────────────────────────────────────────────────

function generateXML(script, creatorProfile) {
  const fps = 30
  const width = 1080
  const height = 1920

  // Convert timecode string "MM:SS" to frame count
  const tcToFrames = (tc) => {
    const [m, s] = tc.split(':').map(Number)
    return (m * 60 + s) * fps
  }

  // Build scene durations
  const scenes = script.scenes.map((scene, i) => {
    const start = tcToFrames(scene.timecode)
    const next = script.scenes[i + 1]
    const end = next ? tcToFrames(next.timecode) : start + 5 * fps
    return { ...scene, startFrame: start, endFrame: end, durationFrames: end - start }
  })

  const totalFrames = scenes[scenes.length - 1].endFrame

  // Wrap text at N chars
  const wrapText = (text, maxLen = 40) => {
    const words = text.split(' ')
    const lines = []
    let line = ''
    for (const w of words) {
      if ((line + ' ' + w).trim().length > maxLen) { lines.push(line.trim()); line = w }
      else line = (line + ' ' + w).trim()
    }
    if (line) lines.push(line.trim())
    return lines.join('\n')
  }

  // Build SRT subtitles block
  const srtLines = scenes.map((sc, i) => {
    const toSrtTime = (frames) => {
      const totalMs = Math.round((frames / fps) * 1000)
      const h = Math.floor(totalMs / 3600000)
      const m = Math.floor((totalMs % 3600000) / 60000)
      const s = Math.floor((totalMs % 60000) / 1000)
      const ms = totalMs % 1000
      return `${String(h).padStart(2,'0')}:${String(m).padStart(2,'0')}:${String(s).padStart(2,'0')},${String(ms).padStart(3,'0')}`
    }
    return `${i + 1}\n${toSrtTime(sc.startFrame)} --> ${toSrtTime(sc.endFrame)}\n${wrapText(sc.caption)}`
  }).join('\n\n')

  // Build FCP XML (xmeml v4)
  const clipItems = scenes.map((sc, i) => `
      <clipitem id="clipitem-v1-${i + 1}">
        <name>${sc.clip_idea || sc.caption}</name>
        <start>${sc.startFrame}</start>
        <end>${sc.endFrame}</end>
        <in>0</in>
        <out>${sc.durationFrames}</out>
        <labels><label2>Caribbean</label2></labels>
        <comments>
          <mastercomment1>${sc.caption.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')}</mastercomment1>
        </comments>
      </clipitem>`).join('\n')

  const captionItems = scenes.map((sc, i) => `
      <clipitem id="clipitem-v2-${i + 1}">
        <name>CAPTION: ${sc.caption.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')}</name>
        <start>${sc.startFrame}</start>
        <end>${sc.endFrame}</end>
        <in>0</in>
        <out>${sc.durationFrames}</out>
      </clipitem>`).join('\n')

  const voiceoverItems = scenes.map((sc, i) => `
      <clipitem id="clipitem-a1-${i + 1}">
        <name>VO: Scene ${i + 1}</name>
        <start>${sc.startFrame}</start>
        <end>${sc.endFrame}</end>
        <in>0</in>
        <out>${sc.durationFrames}</out>
        <comments>
          <mastercomment1>${sc.voiceover.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')}</mastercomment1>
        </comments>
      </clipitem>`).join('\n')

  const markers = scenes.map((sc, i) => `
    <marker>
      <name>Scene ${i + 1}: ${sc.caption.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')}</name>
      <in>${sc.startFrame}</in>
      <out>${sc.startFrame}</out>
    </marker>`).join('\n')

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE xmeml>
<xmeml version="4">
  <!-- Generated by ViralHook AI Studio -->
  <!-- Creator Niche: ${(creatorProfile?.creatorNiche || 'Personal Development').replace(/&/g,'&amp;')} -->
  <!-- Script Concept: ${script.concept.replace(/&/g,'&amp;')} -->
  <!-- Hook Type: ${script.hookType} -->
  <!-- Generation Mode: ${script.modeLabel} -->
  ${script.evaluatorScore ? `<!-- Evaluator Score: ${script.evaluatorScore.overall}/10 -->` : ''}
  <sequence>
    <name>${script.concept.replace(/&/g,'&amp;')}</name>
    <duration>${totalFrames}</duration>
    <rate>
      <timebase>${fps}</timebase>
      <ntsc>FALSE</ntsc>
    </rate>
    <timecode>
      <rate><timebase>${fps}</timebase><ntsc>FALSE</ntsc></rate>
      <string>00:00:00:00</string>
      <frame>0</frame>
      <displayformat>NDF</displayformat>
    </timecode>
    <media>
      <video>
        <format>
          <samplecharacteristics>
            <rate><timebase>${fps}</timebase><ntsc>FALSE</ntsc></rate>
            <width>${width}</width>
            <height>${height}</height>
            <anamorphic>FALSE</anamorphic>
            <pixelaspectratio>square</pixelaspectratio>
            <fielddominance>none</fielddominance>
            <colordepth>32</colordepth>
          </samplecharacteristics>
        </format>
        <!-- V1: Colour placeholder clips (replace with B-roll) -->
        <track>
          ${clipItems}
        </track>
        <!-- V2: Caption / text overlay layer -->
        <track>
          ${captionItems}
        </track>
      </video>
      <audio>
        <!-- A1: Voiceover slots (add recording or TTS audio) -->
        <track>
          ${voiceoverItems}
        </track>
      </audio>
    </media>
    ${markers}
    <logginginfo>
      <description>ViralHook export — ${script.mode} mode</description>
    </logginginfo>
  </sequence>
</xmeml>`

  return { xml, srt: srtLines }
}

// ── Sub-components ──────────────────────────────────────────────────────────

