function ExportButton({ icon: Icon, label, sublabel, color, onClick, disabled, done }) {
  return (
    <button
      onClick={onClick}
      disabled={disabled}
      className={`
        flex items-center gap-4 w-full px-5 py-4 rounded-xl border
        transition-all duration-200 text-left
        ${disabled
          ? 'bg-discord-sidebar border-discord-faint/20 opacity-50 cursor-not-allowed'
          : done
            ? 'bg-discord-green/10 border-discord-green/40 cursor-default'
            : `bg-discord-sidebar border-discord-faint/30 hover:border-${color}/60 hover:bg-discord-hover hover:-translate-y-0.5 shadow-sm hover:shadow-md`
        }
      `}
    >
      <div className={`flex items-center justify-center w-12 h-12 rounded-xl ${done ? 'bg-discord-green/20' : `bg-discord-${color}/15`} flex-shrink-0`}>
        {done
          ? <CheckCircle size={22} className="text-discord-green" />
          : <Icon size={22} className={`text-discord-${color}`} />
        }
      </div>
      <div className="flex-1 min-w-0">
        <p className={`font-semibold text-sm ${done ? 'text-discord-green' : 'text-discord-white'}`}>{done ? `${label} — Done!` : label}</p>
        <p className="text-discord-muted text-xs mt-0.5">{sublabel}</p>
      </div>
      {!done && !disabled && <Download size={18} className="text-discord-muted flex-shrink-0" />}
    </button>
  )
}

// ── Main component ──────────────────────────────────────────────────────────

export default function ExportPhase({ selectedScript, creatorProfile }) {
  const [videoGenerated, setVideoGenerated] = useState(false)
  const [xmlDownloaded, setXmlDownloaded] = useState(false)
  const [generatingVideo, setGeneratingVideo] = useState(false)

  if (!selectedScript) {
    return (
      <div className="flex flex-col h-full bg-discord-bg items-center justify-center">
        <p className="text-discord-muted">No script selected. Go back to Ideation and select a script.</p>
      </div>
    )
  }

  const handleGenerateVideo = async () => {
    setGeneratingVideo(true)
    await new Promise(r => setTimeout(r, 2000))
    setGeneratingVideo(false)
    setVideoGenerated(true)
  }

  const handleGenerateXML = () => {
    const { xml, srt } = generateXML(selectedScript, creatorProfile)

    // Download XML
    const xmlBlob = new Blob([xml], { type: 'application/xml' })
    const xmlUrl = URL.createObjectURL(xmlBlob)
    const xmlLink = document.createElement('a')
    xmlLink.href = xmlUrl
    xmlLink.download = `${selectedScript.concept.replace(/\s+/g, '_')}_viralhook.xml`
    xmlLink.click()
    URL.revokeObjectURL(xmlUrl)

    // Download SRT
    const srtBlob = new Blob([srt], { type: 'text/plain' })
    const srtUrl = URL.createObjectURL(srtBlob)
    const srtLink = document.createElement('a')
    srtLink.href = srtUrl
    srtLink.download = `${selectedScript.concept.replace(/\s+/g, '_')}_viralhook.srt`
    srtLink.click()
    URL.revokeObjectURL(srtUrl)

    setXmlDownloaded(true)
  }

  return (
    <div className="flex flex-col h-full bg-discord-bg overflow-hidden animate-fade-in">
      <ChannelHeader icon="🎬" name="export" topic="Export your script as an Adobe Premiere Pro project file" />

      <div className="flex-1 overflow-y-auto px-6 py-6 max-w-3xl w-full mx-auto space-y-6">

        {/* Selected script summary */}
        <div className="bg-discord-sidebar border border-discord-blurple/30 rounded-xl p-5">
          <div className="flex items-start gap-4">
            <div className="flex items-center justify-center w-12 h-12 rounded-xl bg-discord-blurple/20 flex-shrink-0">
              <Film size={22} className="text-discord-blurple" />
            </div>
            <div className="flex-1 min-w-0">
              <p className="text-discord-muted text-xs font-semibold uppercase tracking-wide mb-1">Selected Script</p>
              <p className="text-discord-white font-bold text-lg leading-tight">{selectedScript.concept}</p>
              <div className="flex items-center gap-3 mt-2 flex-wrap">
                <span className="px-2 py-0.5 bg-discord-blurple/20 text-discord-blurple text-xs font-semibold rounded-full border border-discord-blurple/30">{selectedScript.mode}</span>
                <span className="px-2 py-0.5 bg-purple-500/15 text-purple-400 text-xs font-semibold rounded-full border border-purple-500/30">{selectedScript.hookType}</span>
                <span className="text-discord-muted text-xs flex items-center gap-1">
                  <Clock size={11} /> {selectedScript.scenes.length} scenes
                </span>
                {selectedScript.evaluatorScore && (
                  <span className="text-discord-green text-xs font-semibold flex items-center gap-1">
                    ★ {selectedScript.evaluatorScore.overall}/10
                  </span>
                )}
              </div>
            </div>
          </div>

          {/* Scene preview */}
          <div className="mt-4 pt-4 border-t border-discord-faint/20">
            <p className="text-discord-muted text-xs font-semibold uppercase tracking-wide mb-3">Scene Breakdown</p>
            {selectedScript.scenes.map((scene, i) => (
              <ScenePreviewRow key={i} scene={scene} index={i} />
            ))}
          </div>
        </div>

        {/* Export actions */}
        <div className="space-y-3">
          <p className="text-discord-muted text-xs font-semibold uppercase tracking-wide">Export Options</p>

          {/* Generate Video — cosmetic only */}
          <ExportButton
            icon={Video}
            label="Generate Video"
            sublabel="AI video generation — renders a preview clip (coming soon)"
            color="yellow"
            onClick={handleGenerateVideo}
            disabled={generatingVideo}
            done={videoGenerated}
          />

          {videoGenerated && !xmlDownloaded && (
            <div className="flex items-start gap-2 px-4 py-3 bg-discord-yellow/10 border border-discord-yellow/30 rounded-lg animate-fade-in">
              <AlertTriangle size={15} className="text-discord-yellow flex-shrink-0 mt-0.5" />
              <p className="text-discord-yellow text-xs leading-relaxed">
                Video generation is not yet available in this build. Use "Generate Editable File" to export a fully structured Premiere Pro project you can edit manually.
              </p>
            </div>
          )}

          {/* Generate Editable File — real XML download */}
          <ExportButton
            icon={FileCode}
            label="Generate Editable File"
            sublabel="Downloads Premiere Pro XML + SRT subtitle file — ready to edit"
            color="link"
            onClick={handleGenerateXML}
            disabled={false}
            done={xmlDownloaded}
          />
        </div>

        {/* Post-export instructions */}
        {xmlDownloaded && (
          <div className="bg-discord-sidebar border border-discord-green/30 rounded-xl p-5 animate-slide-up">
            <p className="text-discord-green font-semibold text-sm mb-3 flex items-center gap-2">
              <CheckCircle size={16} /> Files Downloaded Successfully
            </p>
            <ol className="space-y-2 text-discord-text text-sm">
              <li className="flex gap-2"><span className="text-discord-blurple font-bold">1.</span> Open Adobe Premiere Pro</li>
              <li className="flex gap-2"><span className="text-discord-blurple font-bold">2.</span> File → Import → select the <code className="bg-discord-input px-1.5 py-0.5 rounded text-discord-link font-mono text-xs">.xml</code> file</li>
              <li className="flex gap-2"><span className="text-discord-blurple font-bold">3.</span> V1 = colour placeholders (replace with B-roll footage)</li>
              <li className="flex gap-2"><span className="text-discord-blurple font-bold">4.</span> V2 = caption layers (your text overlays, pre-timed)</li>
              <li className="flex gap-2"><span className="text-discord-blurple font-bold">5.</span> A1 = voiceover slots (record or paste TTS audio)</li>
              <li className="flex gap-2"><span className="text-discord-blurple font-bold">6.</span> Import the <code className="bg-discord-input px-1.5 py-0.5 rounded text-discord-link font-mono text-xs">.srt</code> for auto-captioning</li>
            </ol>
          </div>
        )}
      </div>
    </div>
  )
}
